# ─────────────────────────────────────────────────────────────────────────────
#  tens_plane_classes.jl — the orthotropic and the square classes of the plane.
#
#  `TensOrtho` and `TensCubic` carry their dimension. This file holds what their
#  two-dimensional members need of their own: the constructors, the entries and
#  the blocks of their Kelvin-Mandel matrix in the material frame. Everything
#  else (sums, products, inverses, promotions, symmetry blocks) is written once
#  in `tens_anisotropic.jl`, `tens_cubic.jl` and `structured_tens_promotion.jl`
#  on these kernels, for both dimensions.
#
#  In the frame (e₁, e₂), with Pₘ = eₘ⊗eₘ, an orthotropic tensor of the plane is
#
#      order 2:  𝐀 = a₁P₁ + a₂P₂ ,
#      order 4:  ℂ = Σₘₙ Cₘₙ Pₘ⊗Pₙ + 2C₆₆ (P₁⊠ˢP₂ + P₂⊠ˢP₁) ,   C₆₆ = C₁₂₁₂ ,
#
#  and its Kelvin-Mandel matrix in the frame, on (11, 22, √2·12),
#
#      [[C₁₁, C₁₂,  0  ],
#       [C₂₁, C₂₂,  0  ],
#       [ 0,   0,  2C₆₆]] .
#
#  Four constants with the major symmetry (C₂₁ = C₁₂), five without, stored as
#  (C₁₁, C₂₂, C₁₂, C₆₆[, C₂₁]): the order of the three-dimensional class, the
#  diagonal of the normal block, its upper triangle, the shear moduli, then its
#  lower triangle. The group is that of the rectangle, generated by the two
#  mirror lines of the frame.
#
#  The square class is the case C₁₁ = C₂₂: three constants (C₁₁, C₁₂, C₄₄), with
#  C₄₄ = C₁₂₁₂, stored as the coefficients (α, β, γ) of the three projectors of
#  the group of the square,
#
#      𝕁 = ½ v vᵀ, v = (1, 1, 0) ;  𝔼 = ½ w wᵀ, w = (1, −1, 0) ;  𝕋 = (0, 0, 1)(0, 0, 1)ᵀ ,
#
#  α = C₁₁ + C₁₂, β = C₁₁ − C₁₂, γ = 2C₄₄: the plane counterpart of the cubic
#  class, of which it is the restriction to a face of the cube. The isotropic
#  class is β = γ.
#
#  The plane has no transversely isotropic class: an axis in the plane leaves
#  the rectangle group, and an axis normal to it the full rotation group.
# ─────────────────────────────────────────────────────────────────────────────

# ── Constructors ─────────────────────────────────────────────────────────────

# TensOrtho{4}(C₁₁, C₂₂, C₁₂, C₆₆, frame) → TensOrtho{4, 2, T, 4}
function TensOrtho{4}(C11, C22, C12, C66, frame::OrthonormalBasis{2})
    T = promote_type(typeof(C11), typeof(C22), typeof(C12), typeof(C66), eltype(frame))
    return TensOrtho{4, 2, T, 4}((C11, C22, C12, C66), frame)
end

# TensOrtho{4}(C₁₁, C₂₂, C₁₂, C₆₆, C₂₁, frame) → TensOrtho{4, 2, T, 5}
function TensOrtho{4}(C11, C22, C12, C66, C21, frame::OrthonormalBasis{2})
    T = promote_type(typeof(C11), typeof(C22), typeof(C12), typeof(C66), typeof(C21), eltype(frame))
    return TensOrtho{4, 2, T, 5}((C11, C22, C12, C66, C21), frame)
end

# TensOrtho{2}(a₁, a₂, frame) → TensOrtho{2, 2, T, 2}
function TensOrtho{2}(a1, a2, frame::OrthonormalBasis{2})
    T = promote_type(typeof(a1), typeof(a2), eltype(frame))
    return TensOrtho{2, 2, T, 2}((a1, a2), frame)
end

"""
    TensOrtho(C11, C22, C12, C66, frame::OrthonormalBasis{2})
    TensOrtho(C11, C22, C12, C66, C21, frame::OrthonormalBasis{2})

The orthotropic 4th-order tensor **of the plane**, of the four constants of a
major-symmetric one or the five of a general one (`C₂₁` last), in the material
frame `frame`, with `C₆₆ = C₁₂₁₂`: a frame of the plane is `Basis(θ)`, or
`CanonicalBasis{2, T}()`. The order-2 tensor is `TensOrtho{2}(a₁, a₂, frame)`.

```jldoctest
julia> ℂ = TensOrtho(10.0, 6.0, 3.0, 2.0, CanonicalBasis{2, Float64}());

julia> mandel(ℂ)
3×3 Matrix{Float64}:
 10.0  3.0  0.0
  3.0  6.0  0.0
  0.0  0.0  4.0
```
"""
TensOrtho(C11, C22, C12, C66, frame::OrthonormalBasis{2}) = TensOrtho{4}(C11, C22, C12, C66, frame)
TensOrtho(C11, C22, C12, C66, C21, frame::OrthonormalBasis{2}) = TensOrtho{4}(C11, C22, C12, C66, C21, frame)

# From the 3×3 Kelvin-Mandel matrix in the material frame: the upper triangle of
# the normal block, or the whole block with `Val(5)`.
TensOrtho(KMmat::AbstractMatrix, frame::OrthonormalBasis{2}, ::Val{4}) = TensOrtho(KMmat, frame)
TensOrtho(KMmat::AbstractMatrix, frame::OrthonormalBasis{2}, ::Val{5}) =
    TensOrtho{4, 2, eltype(KMmat)}((KMmat[1, 1], KMmat[2, 2], KMmat[1, 2], KMmat[3, 3] / 2, KMmat[2, 1]), frame)
TensOrtho(KMmat::AbstractMatrix, frame::OrthonormalBasis{2}) =
    TensOrtho{4, 2, eltype(KMmat)}((KMmat[1, 1], KMmat[2, 2], KMmat[1, 2], KMmat[3, 3] / 2), frame)

# ── Entries in the canonical basis ───────────────────────────────────────────
#
# `E` is `vecbasis(frame, :cov)`, whose column `m` is the frame vector `eₘ`. The
# shear term is the one of the three-dimensional class for the axes (1, 2).
@inline function _ortho_entry(E, C11, C22, C12, C66, i::Integer, j::Integer, k::Integer, l::Integer)
    @inbounds begin
        P(m, a, b) = E[a, m] * E[b, m]
        return (
            C11 * P(1, i, j) * P(1, k, l)
                + C22 * P(2, i, j) * P(2, k, l)
                + C12 * (P(1, i, j) * P(2, k, l) + P(2, i, j) * P(1, k, l))
                + C66 * (
                E[i, 1] * E[k, 2] * E[j, 2] * E[l, 1] + E[i, 1] * E[l, 2] * E[j, 2] * E[k, 1] +
                    E[j, 1] * E[k, 2] * E[i, 2] * E[l, 1] + E[j, 1] * E[l, 2] * E[i, 2] * E[k, 1] +
                    E[i, 2] * E[k, 1] * E[j, 1] * E[l, 2] + E[i, 2] * E[l, 1] * E[j, 1] * E[k, 2] +
                    E[j, 2] * E[k, 1] * E[i, 1] * E[l, 2] + E[j, 2] * E[l, 1] * E[i, 1] * E[k, 2]
            ) / 2
        )
    end
end

# The general form: the entry of the symmetric part of the normal block, plus
# its skew part `(C₁₂ − C₂₁)/2 (P₁⊗P₂ − P₂⊗P₁)`.
@inline function _ortho_entry(E, C11, C22, C12, C66, C21, i::Integer, j::Integer, k::Integer, l::Integer)
    @inbounds begin
        P(m, a, b) = E[a, m] * E[b, m]
        return _ortho_entry(E, C11, C22, (C12 + C21) / 2, C66, i, j, k, l) +
            (C12 - C21) / 2 * (P(1, i, j) * P(2, k, l) - P(2, i, j) * P(1, k, l))
    end
end

@inline _ortho2_entry(E, a1, a2, i::Integer, j::Integer) = @inbounds a1 * E[i, 1] * E[j, 1] + a2 * E[i, 2] * E[j, 2]

# ── Kelvin-Mandel matrix in the material frame, and its two blocks ───────────

function mandel_material(t::TensOrtho{4, 2, T}) where {T}
    N = _ortho_normal_block(t)
    C66, = _ortho_shears(t)
    z = zero(T)
    return @SMatrix [
        N[1, 1]  N[1, 2]   z  ;
        N[2, 1]  N[2, 2]   z  ;
        z        z      2C66
    ]
end

function _ortho_normal_block(t::TensOrtho{4, 2, T, 4}) where {T}
    C11, C22, C12 = get_data(t)
    return SMatrix{2, 2, T}(C11, C12, C12, C22)
end
function _ortho_normal_block(t::TensOrtho{4, 2, T, 5}) where {T}
    C11, C22, C12, _, C21 = get_data(t)
    return SMatrix{2, 2, T}(C11, C21, C12, C22)
end
_ortho_shears(t::TensOrtho{4, 2}) = (get_data(t)[4],)

_ortho_from_blocks(M::SMatrix{2, 2}, s, frame) =
    TensOrtho{4, 2, promote_type(eltype(M), eltype(frame))}((M[1, 1], M[2, 2], M[1, 2], s..., M[2, 1]), frame)

# On the frame whose two axes are those of the tensor exchanged (up to their
# signs): C₁₁ and C₂₂ exchanged, and C₁₂ with C₂₁; the identity otherwise.
_ortho_on_frame(B::TensOrtho{4, 2, T, 4}, π, ℱ) where {T} =
    (d = get_data(B); TensOrtho{4, 2, T}((d[π[1]], d[π[2]], d[3], d[4]), ℱ))
_ortho_on_frame(B::TensOrtho{4, 2, T, 5}, π, ℱ) where {T} =
    (d = get_data(B); TensOrtho{4, 2, T}((d[π[1]], d[π[2]], π[1] == 1 ? d[3] : d[5], d[4], π[1] == 1 ? d[5] : d[3]), ℱ))
_ortho_on_frame(B::TensOrtho{2, 2, T, 2}, π, ℱ) where {T} = (d = get_data(B); TensOrtho{2, 2, T}((d[π[1]], d[π[2]]), ℱ))

_ortho_general(t::TensOrtho{4, 2, <:Any, 5}) = t
_ortho_general(t::TensOrtho{4, 2, T, 4}) where {T} = (d = get_data(t); TensOrtho{4, 2, T}((d..., d[3]), frame(t)))

# The Kelvin-Mandel matrix of the rotation of the frame, and that of a tensor
# read entry by entry (see `_km_congruence` and `_km_by_entries` in space).
@inline _km_congruence(E::SMatrix{2, 2}) = mandel_rotation(E)

function _km_by_entries(t::AbstractTens{4, 2, T}) where {T}
    s = √(2one(T))
    @inbounds a = t[1, 1, 1, 1], t[2, 2, 1, 1], s * t[2, 1, 1, 1], t[1, 1, 2, 2], t[2, 2, 2, 2], s * t[2, 1, 2, 2],
        s * t[1, 1, 2, 1], s * t[2, 2, 2, 1], s * s * t[2, 1, 2, 1]
    return SMatrix{3, 3, T}(a)
end

# ── Inverse, transpose, symmetry ─────────────────────────────────────────────

# The 2×2 normal block inverted by its adjugate, the shear modulus as
# `1/(4C₆₆)`, the Kelvin-Mandel entry being `2C₆₆`.
function Base.inv(t::TensOrtho{4, 2, T, 4}) where {T}
    C11, C22, C12, C66 = get_data(t)
    inv_det = one(T) / (C11 * C22 - C12 * C12)
    return TensOrtho(C22 * inv_det, C11 * inv_det, -C12 * inv_det, inv(4 * C66), t.frame)
end
function Base.inv(t::TensOrtho{4, 2, T, 5}) where {T}
    C11, C22, C12, C66, C21 = get_data(t)
    inv_det = one(T) / (C11 * C22 - C12 * C21)
    return TensOrtho(C22 * inv_det, C11 * inv_det, -C12 * inv_det, inv(4 * C66), -C21 * inv_det, t.frame)
end

@inline Base.transpose(A::TensOrtho{4, 2, <:Any, 4}) = A
@inline function Base.transpose(A::TensOrtho{4, 2, <:Any, 5})
    C11, C22, C12, C66, C21 = get_data(A)
    return _rebuild(A, (C11, C22, C21, C66, C12))
end

LinearAlgebra.issymmetric(::TensOrtho{4, 2, <:Any, 4}) = true
LinearAlgebra.issymmetric(t::TensOrtho{4, 2, <:Any, 5}) = isequal(get_data(t)[3], get_data(t)[5])

isisotropic(t::TensOrtho{2, 2}) = ((a1, a2) = get_data(t); a1 == a2)

# ── Display ──────────────────────────────────────────────────────────────────

function _show_ortho_terms(io::IO, A::TensOrtho{4, 2, <:Any, 4})
    C11, C22, C12, C66 = get_data(A)
    print(io, "(", C11, ") P₁⊗P₁ + (", C22, ") P₂⊗P₂ + (", C12, ")(P₁⊗P₂+P₂⊗P₁)")
    return print(io, "\n  + 2(", C66, ")(P₁⊠ˢP₂)")
end
function _show_ortho_terms(io::IO, A::TensOrtho{4, 2, <:Any, 5})
    C11, C22, C12, C66, C21 = get_data(A)
    print(io, "(", C11, ") P₁⊗P₁ + (", C22, ") P₂⊗P₂ + (", C12, ") P₁⊗P₂ + (", C21, ") P₂⊗P₁")
    return print(io, "\n  + 2(", C66, ")(P₁⊠ˢP₂)")
end
function _show_ortho_terms(io::IO, A::TensOrtho{2, 2})
    a1, a2 = get_data(A)
    return print(io, "(", a1, ") P₁ + (", a2, ") P₂")
end

# ── The square class ─────────────────────────────────────────────────────────

# The four orthotropic coefficients of a square tensor, C₁₁ = C₂₂.
_ortho_coefficients(t::TensCubic{2}) = ((C₁₁, C₁₂, C₄₄) = cubic_constants(t); (C₁₁, C₁₁, C₁₂, C₄₄))

function mandel_material(t::TensCubic{2, T}) where {T}
    C₁₁, C₁₂, C₄₄ = cubic_constants(t)
    z = zero(T)
    return @SMatrix [
        C₁₁ C₁₂  z  ;
        C₁₂ C₁₁  z  ;
        z   z   2C₄₄
    ]
end

# ── Promotions of the isotropic class of the plane ───────────────────────────

# `α𝕁 + β𝕂` is orthotropic on every frame: C₁₁ = C₂₂ = (α + β)/2,
# C₁₂ = (α − β)/2, C₆₆ = β/2.
function iso_to_ortho(A::TensISO{4, 2, T}, frame::OrthonormalBasis{2}) where {T}
    α, β = get_data(A)
    return TensOrtho((α + β) / 2, (α + β) / 2, (α - β) / 2, β / 2, frame)
end
function iso_to_ortho(A::TensISO{2, 2}, frame::OrthonormalBasis{2})
    λ = get_data(A)[1]
    return TensOrtho{2}(λ, λ, frame)
end

# The sum of two orthotropic tensors of order 2 on different frames: a general
# symmetric tensor, in canonical components.
@noinline function _structured_sum(op::F, A::TensOrtho{2, 2}, B::TensOrtho{2, 2}) where {F}
    a, b = canonical_components(A), canonical_components(B)
    return Tens(Tensors.SymmetricTensor{2, 2}((i, j) -> op(a[i, j], b[i, j])))
end

# ── Random draws ─────────────────────────────────────────────────────────────
#
# As in space: the normal block from the law of the symmetric (or general)
# matrices, the shear eigenvalue 2C₆₆, the frame uniform on the circle.

Random.rand(rng::AbstractRNG, ::Type{TensOrtho{4, 2}}; kwargs...) = rand(rng, TensOrtho{4, 2, Float64, 4}; kwargs...)
function Random.rand(
        rng::AbstractRNG, ::Type{TensOrtho{4, 2, T, 4}}; frame = random_basis(rng, Val(2), T), definite::Bool = false
    ) where {T}
    B = _random_symmetric(rng, T, Val(2), definite)
    return TensOrtho{4}(B[1, 1], B[2, 2], B[1, 2], _random_eigenvalue(rng, T, definite) / 2, frame)
end
function Random.rand(
        rng::AbstractRNG, ::Type{TensOrtho{4, 2, T, 5}}; frame = random_basis(rng, Val(2), T), definite::Bool = false
    ) where {T}
    _refuse_definite(definite, "a TensOrtho{4, 2} of 5 coefficients")
    B = _random_general(rng, T, Val(2))
    return TensOrtho{4}(B[1, 1], B[2, 2], B[1, 2], randn(rng, T) / 2, B[2, 1], frame)
end
Random.rand(rng::AbstractRNG, ::Type{TensOrtho{2, 2}}; kwargs...) = rand(rng, TensOrtho{2, 2, Float64}; kwargs...)
Random.rand(
    rng::AbstractRNG, ::Type{TensOrtho{2, 2, T}}; frame = random_basis(rng, Val(2), T), definite::Bool = false
) where {T} = TensOrtho{2}(ntuple(_ -> _random_eigenvalue(rng, T, definite), Val(2))..., frame)
Random.rand(
    rng::AbstractRNG, ::Type{TensCubic{2, T}}; frame = random_basis(rng, Val(2), T), definite::Bool = false
) where {T} = TensCubic(ntuple(_ -> _random_eigenvalue(rng, T, definite), Val(3))..., frame)

# ── Reductions from space ────────────────────────────────────────────────────
#
# A plane of symmetry of a three-dimensional material carries two plane
# problems. In plane strain the strain normal to the plane vanishes and the
# stiffness of the plane is the block of the stiffness, C_ab; in plane stress
# the normal stress vanishes, σ_k = 0 gives ε_k = −C_kb ε_b / C_kk, and
#
#     C′_ab = C_ab − C_ak C_kb / C_kk ,
#
# the shear modulus of the plane being unchanged in both. The plane tensor is
# written on the canonical basis of the plane, whose axes are the two material
# axes that span it.

# The axes (i, j) of the plane normal to the axis `k`, in the cyclic order.
function _plane_axes(k::Integer)
    1 ≤ k ≤ 3 || throw(ArgumentError("the plane is normal to one of the three axes of the frame; got the axis $k"))
    return mod1(k + 1, 3), mod1(k + 2, 3)
end

"""
    plane_strain_stiffness(ℂ::TensOrtho{4,3}, k = 3) → TensOrtho{4,2}
    plane_strain_stiffness(ℂ::TensCubic{3}) → TensCubic{2}
    plane_strain_stiffness(ℂ::TensTI{4}, Val(:axial)) → TensOrtho{4,2}

The plane-strain stiffness of an anisotropic material in one of its planes of
symmetry: the block of the stiffness in that plane, on the canonical basis of
the plane, whose axes are the material axes that span it.

- An orthotropic tensor, in the plane normal to the axis `k` of its frame: the
  plane axes are the two others in the cyclic order, `(e₁, e₂)` for `k = 3`,
  `(e₂, e₃)` for `k = 1`, `(e₃, e₁)` for `k = 2`. The result is orthotropic in
  the plane, of constants ``(C_{ii}, C_{jj}, C_{ij}, C_{ijij})``.
- A cubic tensor, in a face of its cube: the square class, with the same
  ``(C_{11}, C_{12}, C_{44})``.
- A transversely isotropic tensor, with `Val(:axial)`, in a plane that contains
  its axis: the first plane axis is the axis of the material, the second any
  direction normal to it. With [Hill's moduli](@ref hill_moduli) ``(k, l, m, n, p)``
  the result is orthotropic in the plane, of constants ``(n, k + m, l, p)``.
  Without that argument the plane is normal to the axis and the result isotropic.

See also [`plane_stress_stiffness`](@ref).
"""
function plane_strain_stiffness(ℂ::TensOrtho{4, 3, T, 9}, k::Integer = 3) where {T}
    i, j = _plane_axes(k)
    d = get_data(ℂ)
    n(a, b) = _ortho_normal(d, a, b)
    return TensOrtho{4, 2, T}((n(i, i), n(j, j), n(i, j), d[6 + k]), CanonicalBasis{2, T}())
end
function plane_strain_stiffness(ℂ::TensOrtho{4, 3, T, 12}, k::Integer = 3) where {T}
    i, j = _plane_axes(k)
    d = get_data(ℂ)
    n(a, b) = _ortho_normal(d, a, b)
    return TensOrtho{4, 2, T}((n(i, i), n(j, j), n(i, j), d[6 + k], n(j, i)), CanonicalBasis{2, T}())
end
plane_strain_stiffness(ℂ::TensCubic{3, T}) where {T} = cubic_from_constants(cubic_constants(ℂ)..., CanonicalBasis{2, T}())
function plane_strain_stiffness(ℂ::TensTI{4, T}, ::Val{:axial}) where {T}
    k, l, m, n, p = hill_moduli(ℂ)
    return TensOrtho(n, k + m, l, p, CanonicalBasis{2, T}())
end

"""
    plane_stress_stiffness(ℂ::TensOrtho{4,3}, k = 3) → TensOrtho{4,2}
    plane_stress_stiffness(ℂ::TensCubic{3}) → TensCubic{2}
    plane_stress_stiffness(ℂ::TensTI{4}, Val(:axial)) → TensOrtho{4,2}

The plane-stress stiffness of an anisotropic material in one of its planes of
symmetry, with the planes and the plane axes of [`plane_strain_stiffness`](@ref):
the stress normal to the plane vanishes, and

```math
C'_{ab} = C_{ab} - \\frac{C_{ak}\\,C_{kb}}{C_{kk}} ,
```

``k`` being the normal axis; the shear modulus of the plane is that of the
material. For a transversely isotropic material in a plane that contains its
axis, with Hill's moduli, the constants are
``(n - l^2/(k+m),\\ 4km/(k+m),\\ 2lm/(k+m),\\ p)``.
"""
function plane_stress_stiffness(ℂ::TensOrtho{4, 3, T, 9}, k::Integer = 3) where {T}
    i, j = _plane_axes(k)
    d = get_data(ℂ)
    n(a, b) = _ortho_normal(d, a, b)
    c(a, b) = n(a, b) - n(a, k) * n(k, b) / n(k, k)
    return TensOrtho(c(i, i), c(j, j), c(i, j), d[6 + k], CanonicalBasis{2, T}())
end
function plane_stress_stiffness(ℂ::TensOrtho{4, 3, T, 12}, k::Integer = 3) where {T}
    i, j = _plane_axes(k)
    d = get_data(ℂ)
    n(a, b) = _ortho_normal(d, a, b)
    c(a, b) = n(a, b) - n(a, k) * n(k, b) / n(k, k)
    return TensOrtho(c(i, i), c(j, j), c(i, j), d[6 + k], c(j, i), CanonicalBasis{2, T}())
end
function plane_stress_stiffness(ℂ::TensCubic{3, T}) where {T}
    C₁₁, C₁₂, C₄₄ = cubic_constants(ℂ)
    return cubic_from_constants(C₁₁ - C₁₂^2 / C₁₁, C₁₂ - C₁₂^2 / C₁₁, C₄₄, CanonicalBasis{2, T}())
end
function plane_stress_stiffness(ℂ::TensTI{4, T}, ::Val{:axial}) where {T}
    k, l, m, n, p = hill_moduli(ℂ)
    return TensOrtho(n - l^2 / (k + m), 4 * k * m / (k + m), 2 * l * m / (k + m), p, CanonicalBasis{2, T}())
end
